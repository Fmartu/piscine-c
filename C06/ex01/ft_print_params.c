#include <unistd.h>

int	main(int argc, char **argv)
{
	int	i;
	int	a;
	int	b;

	i = 0;
	a = 1;
	b = 0;
	if (argc > 1)
	{
		while (a < argc)
		{
			while (argv[a][b] != '\0')
			{
				i = argv[a][b];
				write (1, &i, 1);
				b++;
			}
			write(1, "\n", 1);
			b = 0;
			a++;
		}
	}
}
