#include <unistd.h>

int	main(int argc, char **argv)
{
	int	i;
	int	a;

	i = 0;
	if (argc < 1)
		return (0);
	while (argv[0][i] != '\0')
	{
		a = argv[0][i];
		write(1, &a, 1);
		i++;
	}
	write(1, "\n", 1);
}
